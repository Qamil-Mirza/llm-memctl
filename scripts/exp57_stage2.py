def load():
    rows = S0.dev_a()
    metas, P, N = [], np.empty((len(rows), NL * INTER), np.float32), np.empty((len(rows), NL * INTER), np.float32)
    for k, x in enumerate(rows):
        z = np.load(RUN / f"{x['case_id']}.npz")
        m = json.loads(str(z["meta"]))
        assert m["case_id"] == x["case_id"] and m["cls"] == x["cls"]
        metas.append(m)
        P[k] = -z["dhat_P"].reshape(-1); N[k] = -z["dhat_N"].reshape(-1)          # stored as −Δ̂ (= score units)
    return metas, P, N


def k50(s):
    pos = s[s > 0]
    if pos.size == 0:
        return 0, np.array([])
    q = np.sort(pos)[::-1].astype(np.float64)
    c = np.cumsum(q)
    return int(np.searchsorted(c, c[-1] / 2) + 1), q


def verdict_r1(k):
    return "CONCENTRATED" if k <= 50 else "DISTRIBUTED" if k > 500 else "PARTLY CONCENTRATED"


def verdict_r2(lo, hi):
    return "FA-SPECIFIC" if hi <= 0.5 else "SHARED" if lo >= 0.8 else "MIXED"


def boot_k50(M, bases, rng):
    ub = sorted(set(bases))
    idx = {b: [i for i, x in enumerate(bases) if x == b] for b in ub}
    out = []
    for _ in range(N_BOOT):
        w = np.zeros(len(bases), np.float32)
        for b in rng.choice(len(ub), len(ub)):
            w[idx[ub[b]]] += 1
        out.append(k50((w @ M) / w.sum())[0])
    return out


def ratio_boot(per_row, cls, base, num, den, rng):
    ub = sorted(set(base)); bi = {b: [i for i, x in enumerate(base) if x == b] for b in ub}
    out = []
    for _ in range(N_BOOT):
        pick = np.concatenate([bi[ub[b]] for b in rng.choice(len(ub), len(ub))])
        a, d = pick[cls[pick] == num], pick[cls[pick] == den]
        out.append(per_row[a].mean() / per_row[d].mean())
    return np.percentile(out, [2.5, 97.5]).tolist()


def stage1_d():
    """FA − C pooled-SD d of a_i at P_ans from the §56 reads (the exp57_stage1 definition)."""
    import exp57_stage1 as S1
    metas, A, _ = S1.load()
    cls = np.array([m["cls"] for m in metas])
    fa, cc = np.where(cls == "FA")[0], np.where(cls == "C")[0]
    mF, mC = A[fa].mean(0, dtype=np.float64), A[cc].mean(0, dtype=np.float64)
    vF, vC = A[fa].var(0, ddof=1, dtype=np.float64), A[cc].var(0, ddof=1, dtype=np.float64)
    sd = np.sqrt(((len(fa) - 1) * vF + (len(cc) - 1) * vC) / (len(fa) + len(cc) - 2))
    return np.where(sd > 0, (mF - mC) / np.where(sd > 0, sd, 1), 0.0), mF


def write_dirs():
    import exp56_stage1_report as R56
    u51 = np.load(ROOT / "runs/exp51/run/edits/8364bf135ac59a83.npz")["c0_U"][:, 0].astype(np.float64)
    v38 = np.load(ROOT / "runs/exp38_dev/qwen3b/directions.npz")["L29"].astype(np.float64)
    return R56._down_cols, u51, v38


def cosines(K, sign, layers_fn, u51, v38):
    cos = lambda a, b: float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b)))
    W = layers_fn(sorted({int(k // INTER) for k in K}))
    cs = []
    for k, s in zip(K, sign):
        w = W[int(k // INTER)][:, int(k % INTER)].astype(np.float64) * s
        cs.append({"layer": int(k // INTER), "neuron": int(k % INTER), "cos_exp51_U": cos(w, u51), "cos_exp38_v29": cos(w, v38)})
    rng = np.random.default_rng(SEED)
    ref = np.array([(abs(cos(W[l][:, n].astype(np.float64), u51)), abs(cos(W[l][:, n].astype(np.float64), v38)))
                    for l in W for n in rng.choice(INTER, 200, replace=False)])
    return {"per_neuron": cs,
            "mean_abs": {"exp51": float(np.mean([abs(c["cos_exp51_U"]) for c in cs])),
                         "exp38": float(np.mean([abs(c["cos_exp38_v29"]) for c in cs]))},
            "random_same_layers_mean_abs": {"exp51": float(ref[:, 0].mean()), "exp38": float(ref[:, 1].mean())},
            "write": "down_proj column x sign(reset value - FA mean activation in the region)"}


def stage_report():
    metas, SP, SN = load()
    cls = np.array([m["cls"] for m in metas])
    base = [m["base_key"] for m in metas]
    fa = np.where(cls == "FA")[0]
    rp, rn = S0.resets()
    rep: dict = {"n_rows": {c: int((cls == c).sum()) for c in X56.CLASSES}, "regions": {}}
    d, mF_P = stage1_d()
    top50_d, top1000_d = set(np.argsort(-np.abs(d))[:50]), set(np.argsort(-np.abs(d))[:1000])
    K56 = {x["flat"] for x in json.loads((ROOT / "runs/exp56/K.json").read_text())["K"]}
    layers_fn, u51, v38 = write_dirs()
    sets = {}
    for reg, S, rv in (("P", SP, rp.reshape(-1)), ("N", SN, rn.reshape(-1))):
        m = {c: S[cls == c].mean(0, dtype=np.float64) for c in ("FA", "TA", "C", "UA")}
        K50, q = k50(m["FA"])
        rng = np.random.default_rng(SEED)
        bk = boot_k50(S[fa], [base[i] for i in fa], rng)
        lo, hi = np.percentile(bk, [2.5, 97.5])
        order = np.argsort(-m["FA"])
        K = order[:K_N_SIZE]
        per_row = S[:, K].astype(np.float64).sum(1)
        r2 = float(m["TA"][K].sum() / m["FA"][K].sum())
        r2ci = ratio_boot(per_row, cls, base, "TA", "FA", rng)
        cfa = float(m["C"][K].sum() / m["FA"][K].sum())
        cfaci = ratio_boot(per_row, cls, base, "C", "FA", rng)
        sets[reg] = K
        Kl = [{"rank": r + 1, "layer": int(k // INTER), "neuron": int(k % INTER), "flat": int(k),
               "S_FA": float(m["FA"][k]), "S_TA": float(m["TA"][k]), "S_C": float(m["C"][k]), "S_UA": float(m["UA"][k]),
               "reset_value": float(rv[k]), "d_stage1": float(d[k])} for r, k in enumerate(K)]
        (OUT / f"K_{reg}.json").write_text(json.dumps({
            "region": reg, "n": len(Kl), "rule": f"top {K_N_SIZE} by S^{reg} = mean over dev-A FA rows of -dhat_{reg}",
            "reset": "dev-A C-row mean at P_ans (c_mean_act.npy)" if reg == "P" else
                     "dev-A C-row mean over note positions [n_prompt, P_ans) (c_mean_note.npy)",
            "K": Kl}, indent=1))
        rr = {"R1": {"K50": K50, "ci95": [float(lo), float(hi)], "verdict": verdict_r1(K50),
                     "n_positive": int(q.size), "total_positive": float(q.sum()), "net_sum_S_FA": float(m["FA"].sum()),
                     "top_k_share": {str(k): float(q[:k].sum() / q.sum()) for k in (10, 50, 100, 500, 1000, 5000)},
                     "layer_positive_share": (np.clip(m["FA"], 0, None).reshape(NL, INTER).sum(1)
                                              / q.sum()).round(4).tolist()},
              "R2": {"ratio_TA_FA": r2, "ci95": r2ci, "verdict": verdict_r2(*r2ci),
                     "sum_K_S": {c: float(m[c][K].sum()) for c in m}},
              "C_over_FA": {"ratio": cfa, "ci95": cfaci},
              "K_layer_hist": dict(sorted(Counter(int(k // INTER) for k in K).items())),
              "overlap": {"exp56_K": len(set(K.tolist()) & K56), "stage1_top50_abs_d": len(set(K.tolist()) & top50_d),
                          "stage1_top1000_abs_d": len(set(K.tolist()) & top1000_d),
                          "abs_d_ge_0.5": int((np.abs(d[K]) >= 0.5).sum()), "abs_d_ge_1.0": int((np.abs(d[K]) >= 1.0).sum())},
              "K_top10": Kl[:10]}
        if reg == "P":
            rr["cosines"] = cosines(K, np.sign(rv[K] - mF_P[K]), layers_fn, u51, v38)
        rep["regions"][reg] = rr
        log(f"{reg}: K50 {K50} [{lo:.0f}, {hi:.0f}] {verdict_r1(K50)}; R2 {r2:.3f} {r2ci} {verdict_r2(*r2ci)}; "
            f"C/FA {cfa:.3f} {cfaci}")
    rep["overlap_K_P_K_N"] = len(set(sets["P"].tolist()) & set(sets["N"].tolist()))
    rep["D_by_class"] = {c: float(np.mean([m["D"] for m in metas if m["cls"] == c])) for c in X56.CLASSES}
    (OUT / "stage2_report.json").write_text(json.dumps(rep, indent=1))


# ---------------------------------------------------------------------------------------------- K_N tokens

def _offsets(e, ids):
    out, s = [], ""
    for k in range(len(ids)):
        t = e.decode(ids[:k + 1])
        out.append((len(s), len(t))); s = t
    return out, s


def stage_tokens(e):
    import re
    KN = json.loads((OUT / "K_N.json").read_text())["K"]
    lay = sorted({x["layer"] for x in KN})
    rp, rn = S0.resets()
    at = X.Attributor(e, rp, rn, grad_from=0)
    cases = {c["case_id"]: c for c in X56.cases()}
    tot = Counter(); npos = Counter(); act_sum = np.zeros(len(KN)); act_n = 0
    per_row = []
    for x in S0.dev_a("FA"):
        r, rec = S0.case_rec(x["case_id"])
        res = at.run(rec, X56.city_ids(e.encode, r), keep_ag=True)
        n0, p = res["n_prompt"], res["p_ans"]
        c = np.zeros(p - n0)
        for k, z in enumerate(KN):
            a, g = res["ag"][z["layer"]]
            ai, gi = a[n0:p, z["neuron"]], g[n0:p, z["neuron"]]
            c += (z["reset_value"] - ai) * gi
            act_sum[k] += ai.sum()
        act_n += p - n0
        gen = rec["gen_ids"][:rec["j"]]
        offs, text = _offsets(e, gen)
        assert text.endswith("Answer:"), text[-20:]
        mk = text.rfind("\nAnswer") if "\nAnswer" in text else text.rfind("Answer")
        gold = [(m.start(), m.end()) for m in re.finditer(re.escape(cases[x["case_id"]]["gold"]), text)]
        cats = []
        for t in range(p - n0):
            s, f = offs[t]
            w = re.sub(r"[^a-z]", "", e.decode([gen[t]]).lower())
            if s >= mk:
                cats.append("MARKER")
            elif any(s < ge and f > gs for gs, ge in gold):
                cats.append("GOLD")
            elif w in HEDGES:
                cats.append("HEDGE")
            else:
                cats.append("OTHER")
        for t, cat in enumerate(cats):
            tot[cat] += -c[t]; npos[cat] += 1
        per_row.append({"case_id": x["case_id"], "sum_minus_c": float(-c.sum()),
                        "by_cat": {k: float(sum(-c[t] for t in range(len(cats)) if cats[t] == k)) for k in set(cats)},
                        "top_tokens": [(e.decode([gen[t]]), cats[t], float(-c[t])) for t in np.argsort(c)[:3]]})
        del res
    T, NP = sum(tot.values()), sum(npos.values())
    layers_fn, u51, v38 = write_dirs()
    mean_fa = act_sum / act_n
    K = np.array([z["flat"] for z in KN])
    cs = cosines(K, np.sign(np.array([z["reset_value"] for z in KN]) - mean_fa), layers_fn, u51, v38)
    rep = {"categories": {k: {"share_of_minus_c": float(tot[k] / T), "share_of_positions": npos[k] / NP,
                              "sum_minus_c": float(tot[k]), "n_positions": npos[k]} for k in ("GOLD", "HEDGE", "MARKER", "OTHER")},
           "total_minus_c": float(T), "n_rows": len(per_row), "cosines_K_N": cs, "rows": per_row}
    (OUT / "stage2_tokens.json").write_text(json.dumps(rep, indent=1, ensure_ascii=False))
    log(json.dumps(rep["categories"]))


