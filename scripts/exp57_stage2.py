def grid_arms(unk, full=True):
    rp, rn = S0.resets()
    arms = [{"name": "base"}]
    rng = np.random.default_rng(5900)
    for reg, rv in (("P", rp), ("N", rn)):
        K = np.array([x["flat"] for x in json.loads((OUT / f"K_{reg}.json").read_text())["K"]])
        spec = lambda ks: [(l, [int(k % INTER) for k in ks if k // INTER == l],
                            [float(rv[l, k % INTER]) for k in ks if k // INTER == l])
                           for l in sorted({int(k // INTER) for k in ks})]
        arms.append({"name": f"K_{reg}", f"reset_{reg}": spec(K)})
        if full:
            lay = np.bincount(K // INTER, minlength=NL)
            for j in range(20):
                ks = []
                for l in np.where(lay > 0)[0]:
                    pool = np.setdiff1d(np.arange(INTER), K[K // INTER == l] % INTER)
                    ks += [l * INTER + int(i) for i in rng.choice(pool, lay[l], replace=False)]
                arms.append({"name": f"R_{reg}{j:02d}", f"reset_{reg}": spec(np.array(ks))})
    arms.append({"name": "B1_cal", "bias": {"ids": [unk], "value": -8.0}})
    arms += [{"name": f"G{b}", "bias": {"ids": [unk], "value": -float(b)}} for b in GRID]
    return arms


def stage_equality_grid(e):
    import exp57_arms as A
    unk = e.encode(X56.UNK_TEXT)[0]
    fa = S0.dev_a("FA"); ta = S0.dev_a("TA")
    plan = [(fa[7]["case_id"], True), (fa[21]["case_id"], True), (ta[0]["case_id"], False)]
    out, times = [], []
    for cid, full in plan:
        _, rec = S0.case_rec(cid)
        t_star = int(json.loads(str(np.load(ROOT / "runs/exp56/run/stage1" / f"{cid}.npz")["meta"]))["t_star"])
        arms = grid_arms(unk, full)
        rows, tb, tr = A.compare(e, rec, arms, unk, t_star)
        for x in rows:
            x["case_id"] = cid
        out += rows
        times.append({"case_id": cid, "n_arms": len(arms), "n_ids": len(CM.prefix_ids(rec)), "batched_s": tb,
                      "batch1_s": tr})
        log(f"{cid}: {sum(x['same'] for x in rows)}/{len(rows)} same, max dD {max(x['dD'] for x in rows):.2e}, "
            f"batched {tb:.0f} s ({len(arms)} arms), batch-1 {tr:.0f} s")
    rep = {"n_row_arms": len(out), "same_frac": float(np.mean([x["same"] for x in out])),
           "max_dD": float(max(x["dD"] for x in out)),
           "PASS": bool(all(x["same"] for x in out) and max(x["dD"] for x in out) <= 1e-3),
           "differences": [x for x in out if not x["same"] or x["dD"] > 1e-3], "times": times,
           "peak_rss_gb": EN.peak_rss_gb()}
    (OUT / "equality_grid.json").write_text(json.dumps(rep, indent=1))
    (OUT / "equality_grid_rows.json").write_text(json.dumps(out, indent=1, ensure_ascii=False))
    log(json.dumps({k: v for k, v in rep.items() if k != "differences"}))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", choices=["read", "report", "tokens", "devb-una", "equality-grid"])
    a = ap.parse_args(argv)
    if a.stage == "report":
        return stage_report()
    e = EN.load("hf")
    log(f"engine {e.name} loaded in {e.load_s:.0f} s")
    return {"read": stage_read, "tokens": stage_tokens, "devb-una": stage_devb_una,
            "equality-grid": stage_equality_grid}[a.stage](e)


if __name__ == "__main__":
    sys.exit(main())
