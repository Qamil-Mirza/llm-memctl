"""§57 stage 2 (proposal rev 0 + 0a, 9e51a1b / 476a580; freeze runs/exp57/freeze.json at 3501a72): rank every neuron by
its total-effect reset score on dev-A, freeze K_P and K_N, descriptives; then the dev-B UNA generation and the
equality check of the stage-3 arms with the rev-0a B1 grid. Laptop, $0.

    HF_HUB_OFFLINE=1 .venv/bin/python scripts/exp57_stage2.py read          # runs/exp57/run/stage2/<case>.npz (resumable)
    .venv/bin/python scripts/exp57_stage2.py report                         # R1, K_P.json, K_N.json, R2, descriptives
    HF_HUB_OFFLINE=1 .venv/bin/python scripts/exp57_stage2.py tokens        # K_N by note-token category + K_N cosines
    HF_HUB_OFFLINE=1 .venv/bin/python scripts/exp57_stage2.py devb-una      # 300 dev-B UNA rows, §55 P0 settings
    HF_HUB_OFFLINE=1 .venv/bin/python scripts/exp57_stage2.py equality-grid # 2 FA + 1 TA dev-A rows, stage-3 arms + grid

Fixed here, before any stage-2 number is seen:
- Read: Attributor (grad_from 0 per freeze) on every dev-A class row (FA 140, C 305, TA 289, UA 9); stores Δ̂_P and
  Δ̂_N (36 × 11,008 float32 each), D and t*.
- S^R_i = mean over dev-A FA rows of −Δ̂^R_i (positive = the reset lowers D). R1: K50 on the positive part of S^R
  (fewest neurons whose summed S reaches half the positive total); 95% interval from 2,000 base-clustered draws over
  the bases with an FA row (seed 56, resampling only); verdict on the point (≤ 50 CONCENTRATED, > 500 DISTRIBUTED).
- K_R = the top 50 by S^R. Reset values: ā^C_P (P) and ā^C_N (N), as frozen.
- R2 per set: Σ_K (mean over TA rows of −Δ̂) / Σ_K (mean over FA rows of −Δ̂); 95% interval from 2,000 draws over all
  75 dev-A bases (FA and TA rows of a base together), K fixed (seed 56). FA-SPECIFIC if wholly ≤ 0.5, SHARED if wholly
  ≥ 0.8, MIXED otherwise. C/FA the same way (descriptive).
- Stage-1 link: d_i = the FA − C pooled-SD difference of a_i at P_ans (§56 reads, as in exp57_stage1); overlaps of
  each K with the top 50 and top 1,000 by |d| and the count with |d| ≥ 0.5 / ≥ 1.0.
- Cosines (K_P here, K_N in `tokens`): write vector = down_proj column × sign(ā^C − FA mean activation in the region),
  i.e. the direction the reset adds; against the §51 rank-1 U (8364bf13 c0_U) and §38 v_29, with 200 random neurons
  per K layer as baseline (|cos|).
- Tokens (K_N, FA rows): per note position t, c(t) = Σ_{i∈K_N} (ā^C_N,i − a_i(t)) · ∂D/∂a_i(t). Categories, in this
  order: MARKER = positions whose text lies in the final "\\nAnswer" before ':'; GOLD = positions overlapping a
  mention of the row's gold city in the note; HEDGE = tokens whose letters (lower-case, apostrophes removed) are in
  HEDGES; OTHER = the rest. Reported: share of Σ(−c) per category (pooled over FA rows) and share of positions.
- dev-B UNA: the 300 rows of runs/exp56/devb_una_todo.jsonl with the P0 prompt (frozen prompt; asserted unchanged by
  exp55_prompts.build(·, "P0")), generated by exp55_run.run_free (§51 run_b0, batched 64 in case-id order, 256 new
  tokens, §51 grader) into runs/exp56/run/devb_una/b0/W/. Class counts by exp56_common.klass.
- Equality (rev 0a): dev-A FA rows at equality positions 7 and 21 (53 arms: base, K_P, K_N, 20 random P, 20 random N
  matched to each K's per-layer counts with default_rng(5900), B1 at the dev-A b placeholder −8, and the 9 non-zero
  grid values b ∈ {1, 2, 3, 4, 5, 6, 8, 10, 12} as −b on " unknown" at step 0), and the first dev-A TA row (13 arms:
  base, K_P, K_N, B1 −8, 9 grid). Pass: all greedy outputs identical, |ΔD0| ≤ 1e-3. The random sets here are
  stand-ins for the equality check only; stage 3 freezes its own.
"""
