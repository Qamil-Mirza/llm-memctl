# --- populations -------------------------------------------------------------------------------------------------

def is_marked(rec) -> bool:
    return sel.split_note(rec.output)[0] is not None


def cached_refusal(rec) -> bool:
    return sel.is_refusal_answer(sel.agent_answer(rec.output)[0])


@dataclass
class Populations:
    by_q: dict
    G: list[str]
    P0: list[str]
    excluded_unanswerable: list[str]


def populations(records) -> Populations:
    from memctl.jacobian_data import family_population
    by_q = {r.question_id: r for r in records}
    in_pop = {r.question_id for r in family_population(records)}
    G = sorted(q for q, r in by_q.items() if q in in_pop and is_marked(r) and cached_refusal(r))
    P0 = sorted(q for q, r in by_q.items() if is_marked(r) and r.answerable and not r.all_in_view and cached_refusal(r))
    unans = sorted(q for q, r in by_q.items() if is_marked(r) and not r.answerable and not r.all_in_view and cached_refusal(r))
    if set(G) & set(P0):
        raise AssertionError(f"gate and estimation rows overlap: {sorted(set(G) & set(P0))}")
    return Populations(by_q, G, P0, unans)


def load_records(folds, runs_dir: str = "runs"):
    from memctl.jacobian_data import load_family_records
    out = []
    for f in folds:
        out += load_family_records(FAMILY, f, runs_dir)[0]
    return out


# --- the gate ----------------------------------------------------------------------------------------------------

def gate_order(settings: list[st.Setting]) -> list[st.Setting]:
    """Rule order: deeper layer first, then smaller alpha (rev 1: 'ties resolved toward the deeper layer and the
    smaller alpha'; every passing setting ties on the gate)."""
    return sorted(settings, key=lambda s: (-s.layer, s.alpha))


def alt_order(settings: list[st.Setting], steer_ans: dict[str, int]) -> list[st.Setting]:
    """Descriptive only: the §38-style order, highest Steer answers first, then the rev 1 tie-break."""
    return sorted(settings, key=lambda s: (-steer_ans.get(s.key, -1), -s.layer, s.alpha))


def counts(rows: list[dict]) -> dict:
    return {"n": len(rows), "ans": sum(r["cls"] == "answer" for r in rows),
            "degenerate": sum(r["cls"] == "degenerate" for r in rows),
            "refusal": sum(r["cls"] == "refusal" for r in rows),
            "gold": sum(bool(r["gold_d1_provisional"]) for r in rows)}


def ans_min(n: int) -> int:
    """The answer bar on n reproduced G rows: ceil(ANS_SHARE x n), 7 when all 13 reproduce."""
    return math.ceil(ANS_SHARE * n)


def setting_gate(steer: dict, cut: dict | None, rnd: dict | None) -> dict:
    """One setting's gate arithmetic from row counts (None: that arm not run). Criteria in rev 1 order; the answer
    bar scales with the reproduced rows (steer['n'])."""
    out = {"steer": steer, "cut": cut, "random": rnd, "ans_min": ans_min(steer["n"]),
           "ans_ok": steer["ans"] >= ans_min(steer["n"]), "degen_ok": steer["degenerate"] <= DEGEN_MAX}
    out["gold_diff"] = None if cut is None else steer["gold"] - cut["gold"]
    out["gold_ok"] = None if cut is None else out["gold_diff"] >= GOLD_DIFF_MIN
    out["random_bound"] = RANDOM_SHARE * steer["ans"]
    out["random_ok"] = None if rnd is None else rnd["ans"] <= out["random_bound"]
    checks = [out["ans_ok"], out["degen_ok"], out["gold_ok"], out["random_ok"]]
    out["pass"] = False if False in checks else (None if None in checks else True)
    return out


def needs_cut(steer: dict) -> bool:
    return steer["ans"] >= ans_min(steer["n"]) and steer["degenerate"] <= DEGEN_MAX


# --- full generation (N, N-cut) ----------------------------------------------------------------------------------

def full_generate(engine, prepared: st.Prepared, max_new: int) -> tuple[list[int], float]:
    """Greedy from the prepared prefix with no newline stop and no hook: until a stop id or `max_new` tokens."""
    import copy
    import torch
    t0 = time.perf_counter()
    cache = copy.deepcopy(prepared.cache)
    gen: list[int] = []
    with torch.no_grad():
        logits = engine._step(prepared.last_id, cache)
        while True:
            nxt = int(logits.argmax())
            if nxt in engine.stop_ids:
                break
            gen.append(nxt)
            if len(gen) >= max_new:
                break
            logits = engine._step(nxt, cache)
    return gen, time.perf_counter() - t0


# --- the run -----------------------------------------------------------------------------------------------------

class Run:
    def __init__(self, engine, pops: Populations, out: Path, layers, alphas, n_check: int, log=print) -> None:
        self.engine, self.p, self.log = engine, pops, log
        self.dir = out / READER
        self.layers, self.alphas, self.n_check = list(layers), [float(a) for a in alphas], n_check
        self.final = st.final_layer(engine.n_layers)
        self.wsha = st.sha256(json.dumps({"steering": st.wording(MAX_NEW), "family": FAMILY.stamp(),
                                          "full_max_new": MAX_NEW_FULL}, sort_keys=True))
        self.vectors: dict = {}
        self.ncut: dict[str, str] = {}
        self._rows: dict[str, dict] = {}
        self.passes = {"prefills": 0, "generations": 0, "tokens_generated": 0}

    # files
    def path(self, stage: str) -> Path:
        return self.dir / f"{stage}.jsonl"

    def rows(self, stage: str) -> dict:
        if stage not in self._rows:
            self._rows[stage] = {st.row_key(r): r for r in read_jsonl(self.path(stage))}
        return self._rows[stage]

    def write_json(self, name: str, obj) -> None:
        self.dir.mkdir(parents=True, exist_ok=True)
        (self.dir / name).write_text(json.dumps(obj, indent=1, default=float))

    def resid_path(self, kind: str, q: str) -> Path:
        return self.dir / "resid" / kind / f"{q}.npy"

    def check_manifest(self) -> None:
        m = {"engine": self.engine.name, "model": self.engine.model, "family": FAMILY.stamp(), "layers": self.layers,
             "alphas": self.alphas, "unit": UNIT, "max_new_tokens": MAX_NEW, "max_new_full": MAX_NEW_FULL,
             "wording_sha256": self.wsha, "classifier": st.CLASSIFIER_VERSION, "gate_rule": GATE_RULE,
             "G": self.p.G, "P0": self.p.P0, "n_check": self.n_check,
             "G_gold_in_cached_note": {q: bool(sel.gold_in_note(self.p.by_q[q])) for q in self.p.G}}
        path = self.dir / "manifest.json"
        if path.exists():
            old = json.loads(path.read_text())
            for k in ("engine", "model", "family", "layers", "alphas", "unit", "max_new_tokens", "wording_sha256", "G", "P0"):
                if old.get(k) != m[k]:
                    raise SystemExit(f"REFUSED: {path} has {k} = {old.get(k)!r}, this run {m[k]!r}; one engine and one "
                                     "grid per run directory (move it aside)")
        self.write_json("manifest.json", m)

    # inputs
    def item(self, kind: str, q: str) -> st.SteerInput:
        rec = self.p.by_q[q]
        if kind == "cut":
            return st.cut_input(rec, self.ncut[q])
        if kind in ("N", "Ncut"):
            ai = sel.build_arm_input(rec, kind)
            return st._make(kind, rec, ai.prompt, "")
        return st.arm_input(rec, kind)

    def stamp(self, row: dict) -> dict:
        row["wording_sha256"] = self.wsha
        row["family"] = READER
        return row

    def do(self, stage: str, pop: str, kind: str, q: str, settings: list[st.Setting], capture: bool = False,
           own_state=None, b_state=None) -> dict:
        item = self.item(kind, q)
        done = self.rows(stage)
        out, todo = {}, []
        for s in settings:
            vec = st.hook_vector(s, self.vectors, own_state, b_state, self.engine.hidden)
            old = done.get((pop, kind, s.key, q))
            if old is not None and (not capture or self.resid_path(kind, q).exists()):
                st.check_row(old, item, self.engine.name, self.wsha, vec)
                out[s.key] = old
            else:
                todo.append((s, vec))
        if not todo:
            return out
        prepared = self.engine.prepare(item)
        self.passes["prefills"] += 1
        if not self.engine.last_token_text(prepared).endswith(":"):
            self.log(f"  WARNING {kind}/{q}: last prompt token {self.engine.last_token_text(prepared)!r}, not ':'")
        gold = self.p.by_q[q].gold
        new = []
        for s, vec in todo:
            specs = st.specs_for(s, self.vectors, own_state, b_state, self.engine.hidden)
            gen = self.engine.run(prepared, specs, MAX_NEW, capture=tuple(range(self.engine.n_layers)) if capture else ())
            self.passes["generations"] += 1
            self.passes["tokens_generated"] += gen.n_new
            if capture:
                arr = np.stack([gen.captured[L] for L in range(self.engine.n_layers)]).astype(np.float32)
                self.resid_path(kind, q).parent.mkdir(parents=True, exist_ok=True)
                np.save(self.resid_path(kind, q), arr)
            row = self.stamp(st.make_row(stage, pop, item, s, gen, self.engine, prepared, vec, MAX_NEW, gold, READER))
            new.append(row)
            out[s.key] = row
        append_jsonl(self.path(stage), new)
        self.rows(stage).update({st.row_key(r): r for r in new})
        for r in new:
            self.log(f"  [{stage} {pop} {kind} {r['setting']['key']}] {q} {r['cls']:10s} {r['phrase']!r:.50}")
        return out

    def full(self, stage: str, kind: str, q: str) -> dict:
        """One full generation (N or Ncut), resumable; the text is stored stripped (as the §23 server returned it)."""
        item = self.item(kind, q)
        done = self.rows(stage)
        old = done.get((kind, kind, "none", q))
        if old is not None:
            st.check_row(old, item, self.engine.name, self.wsha, None)
            return old
        prepared = self.engine.prepare(item)
        gen, dt = full_generate(self.engine, prepared, MAX_NEW_FULL)
        self.passes["prefills"] += 1
        self.passes["generations"] += 1
        self.passes["tokens_generated"] += len(gen)
        text = self.engine.decode(gen).strip()
        answer, marker = sel.agent_answer(text)
        row = {"stage": stage, "pop": kind, "kind": kind, "question_id": q, "fold": item.fold, "reader": READER,
               "family": READER, "engine": self.engine.name, "model": self.engine.model, "wording_sha256": self.wsha,
               "input_sha256": item.input_sha256, "intact_prompt_sha256": item.intact_prompt_sha256,
               "setting": st.Setting("none").to_dict(), "vector_sha256": None, "n_input_tokens": len(prepared.ids),
               "max_new_tokens": MAX_NEW_FULL, "generated": text, "gen_ids": gen, "n_new": len(gen),
               "first_id_stripped": (self.first_id_after_chat(item.prompt, text) if text else None),
               "final_answer": answer, "marker": marker, "refusal": sel.is_refusal_answer(answer),
               "timing": {"prefill_s": prepared.prefill_s, "gen_s": dt}}
        append_jsonl(self.path(stage), [row])
        done[st.row_key(row)] = row
        self.log(f"  [{stage} {kind}] {q} marker {marker} refusal {row['refusal']} {answer!r:.40} ({len(gen)} tokens)")
        return row

    def first_id_after_chat(self, prompt: str, text: str) -> int | None:
        chat = self.engine.chat_text(prompt)
        a, b = self.engine.encode(chat), self.engine.encode(chat + text)
        return b[len(a)] if b[:len(a)] == a and len(b) > len(a) else None

    # stage i
    def reproduction(self) -> dict:
        none = st.Setting("none")
        res = {"G": {}, "P0": {}}
        for pop, qs in (("G", self.p.G), ("P0", self.p.P0)):
            for q in qs:
                rec = self.p.by_q[q]
                a = self.do("repro", pop, "A", q, [none], capture=(pop == "P0"))["none"]
                note, cached_ans = sel.split_note(rec.output)
                try:
                    cached_first = st.continuation_first_id(self.engine, sel.frozen_continuation("A", note), cached_ans)
                except ValueError:          # the cached answer re-tokenises the marker, or is empty
                    cached_first = None
                entry = {"A_refusal": a["refusal"], "cached_refusal": True, "ok": bool(a["refusal"]),
                         "first_match": a["first_token"] == cached_first,
                         "phrase_match": a["final_answer"].strip() == sel.agent_answer(rec.output)[0].strip()}
                if pop == "P0":
                    b = self.do("repro", pop, "B", q, [none], capture=True)["none"]
                    entry.update({"B_refusal": b["refusal"], "B_cls": b["cls"], "B_phrase": b["phrase"],
                                  "pair": entry["ok"] and not b["refusal"]})
                res[pop][q] = entry
        n = len(res["G"]) + len(res["P0"])
        ok = sum(v["ok"] for p in ("G", "P0") for v in res[p].values())
        res["G_ok"] = [q for q, v in res["G"].items() if v["ok"]]
        res["pairs"] = [q for q, v in res["P0"].items() if v.get("pair")]
        res["rate"] = ok / n if n else None
        res["rate_G"] = len(res["G_ok"]) / len(res["G"]) if res["G"] else None
        res["first_match"] = sum(v["first_match"] for p in ("G", "P0") for v in res[p].values())
        res["phrase_match"] = sum(v["phrase_match"] for p in ("G", "P0") for v in res[p].values())
        res["n"] = n
        res["pass"] = res["rate"] is not None and res["rate"] >= st.REPRO_GATE
        return res

    def n_check_rows(self) -> dict:
        res = {}
        for q in self.p.G[:self.n_check]:
            rec = self.p.by_q[q]
            row = self.full("ncheck", "N", q)
            cached = rec.output.strip()
            res[q] = {"first_match": row["first_id_stripped"] == self.first_id_after_chat(rec.prompt, cached),
                      "marker": row["marker"], "refusal_match": row["refusal"] == cached_refusal(rec),
                      "exact": row["generated"] == cached}
        k = lambda key: sum(v[key] for v in res.values())  # noqa: E731
        bar = min(4, len(res)) if len(res) < 5 else 4
        out = {"rows": res, "n": len(res), "first_match": k("first_match"), "marker": k("marker"),
               "refusal_match": k("refusal_match"), "exact": k("exact"),
               "bar": f">= {bar} of {len(res)} first id and marker (stage 0 D-22, >= 4 of 5)"}
        out["pass"] = (not res) or (out["first_match"] >= bar and out["marker"] >= bar)
        return out

    # stage iii
    def directions(self, pairs: list[str]) -> dict:
        ra = {q: np.load(self.resid_path("A", q)) for q in pairs}
        rb = {q: np.load(self.resid_path("B", q)) for q in pairs}
        out, arrays = {}, {}
        for L in self.layers:
            v = st.estimate_direction(ra, rb, pairs, L)
            stats = st.direction_stats(v, ra, pairs, L)
            out[str(L)] = stats
            arrays[f"L{L}"] = v
            for a in self.alphas:
                self.vectors[(L, a, UNIT)] = st.scaled_vector(v, a, UNIT, stats["mean_resid_A_norm"])
        np.savez(self.dir / "directions.npz", **arrays)
        self.write_json("directions.json", {"pairs": pairs, "layers": out})
        return out

    # stage iv
    def sanity(self, pairs: list[str]) -> dict:
        repro = self.rows("repro")
        fin, zero, self_ex = [], [], []
        for q in pairs:
            ra, rb = np.load(self.resid_path("A", q)), np.load(self.resid_path("B", q))
            a0, b0 = repro[("P0", "A", "none", q)], repro[("P0", "B", "none", q)]
            settings = ([st.Setting("overwrite_B", self.final), st.Setting("overwrite_self", self.final)]
                        + [st.Setting("zero", L) for L in self.layers])
            rows = self.do("sanity", "pairs", "A", q, settings, own_state=ra, b_state=rb)
            same = lambda r: r["generated"] == a0["generated"] and r["gen_ids"] == a0["gen_ids"]  # noqa: E731
            fin.append(rows[f"overwrite_B:L{self.final}"]["first_token"] == b0["first_token"])
            self_ex.append(same(rows[f"overwrite_self:L{self.final}"]))
            zero += [same(rows[f"zero:L{L}"]) for L in self.layers]
        out = st.sanity_summary(fin, zero, self_ex, [])
        out["final_layer"] = self.final
        return out

    # stage v
    def settings(self) -> list[st.Setting]:
        return st.sweep_settings(self.layers, self.alphas, UNIT)

    def arm_counts(self, stage: str, kind: str, mode: str, s: st.Setting, G: list[str]) -> dict | None:
        rows = self.rows(stage)
        key = s.key if mode == "steer" else st.Setting(mode, s.layer, s.alpha, s.unit).key
        got = [rows[("G", kind, key, q)] for q in G if ("G", kind, key, q) in rows]
        return counts(got) if len(got) == len(G) and G else None

    def gate(self, G: list[str]) -> dict:
        table, order = {}, []
        for s in self.settings():
            steer = self.arm_counts("sweep", "A", "steer", s, G)
            cut = self.arm_counts("cut", "cut", "steer", s, G)
            rnd = self.arm_counts("random", "A", "random", s, G)
            table[s.key] = {"layer": s.layer, "alpha": s.alpha, **setting_gate(steer, cut, rnd)}
        for s in gate_order(self.settings()):
            order.append(s.key)
        chosen = next((k for k in order if table[k]["pass"] is True), None)
        steer_ans = {k: v["steer"]["ans"] for k, v in table.items()}
        alt = next((s.key for s in alt_order(self.settings(), steer_ans) if table[s.key]["pass"] is True), None)
        a_cut = counts([self.rows("cut")[("G", "cut", "none", q)] for q in G if ("G", "cut", "none", q) in self.rows("cut")])
        return {"rule": GATE_RULE, "n_G": len(G), "table": table, "order": order, "chosen": chosen,
                "alt_rule_choice": alt, "a_cut": a_cut,
                "status": "chosen" if chosen else "none"}

    def sweep(self, G: list[str]) -> dict:
        settings = self.settings()
        for q in G:
            self.do("sweep", "G", "A", q, settings)
        for q in G:
            self.ncut[q] = self.full("ncut", "Ncut", q)["generated"]
        # Steer-cut (and the unsteered A-cut) at every setting whose Steer row can still pass, one prefill per row
        cut_settings = [s for s in gate_order(settings) if needs_cut(self.arm_counts("sweep", "A", "steer", s, G))]
        for q in G:
            self.do("cut", "G", "cut", q, [st.Setting("none")] + cut_settings)
        # Random at candidates in rule order: the first setting passing the other three criteria gets Random; if
        # Random passes it is chosen, otherwise the walk goes on to the next candidate
        for key in self.gate(G)["order"]:
            e = self.gate(G)["table"][key]
            if not (e["ans_ok"] and e["degen_ok"] and e["gold_ok"]):
                continue
            if e["random"] is None:
                s = st.setting_from_key(key)
                self.log(f"Random at candidate {key}")
                for q in G:
                    self.do("random", "G", "A", q, [st.Setting("random", s.layer, s.alpha, s.unit)])
            if self.gate(G)["table"][key]["pass"]:
                break
        return self.gate(G)


# --- timing ------------------------------------------------------------------------------------------------------

def timing(run: Run) -> dict:
    recs = []
    for q in run.p.G[:st.TIMING_N]:
        prepared = run.engine.prepare(run.item("A", q))
        g0 = run.engine.run(prepared, [], MAX_NEW)
        g1 = run.engine.run(prepared, [st.add_spec(run.layers[len(run.layers) // 2], np.zeros(run.engine.hidden, np.float32))],
                            MAX_NEW)
        for g in (g0, g1):
            recs.append({"n_prefix": prepared.n_prefix, "prefill_s": prepared.prefill_s, "copy_s": g.copy_s,
                         "first_step_s": g.first_step_s, "decode_s": g.decode_s, "n_new": g.n_new})
    pre = {(r["n_prefix"], r["prefill_s"]) for r in recs}
    rate_p = sum(s for _, s in pre) / sum(n for n, _ in pre)
    dec = [r for r in recs if r["n_new"] > 1]
    rate_d = (sum(r["decode_s"] for r in dec) / sum(r["n_new"] - 1 for r in dec)) if dec else \
        sum(r["first_step_s"] for r in recs) / len(recs)
    return {"rows": len(recs) // 2, "prefill_s_per_token": rate_p, "decode_s_per_token": rate_d,
            "first_step_s": sum(r["first_step_s"] for r in recs) / len(recs),
            "copy_s": sum(r["copy_s"] for r in recs) / len(recs),
            "mean_new_tokens_unsteered": sum(r["n_new"] for r in recs) / len(recs), "records": recs}


def projection(run: Run, t: dict, n_pairs: int | None = None) -> dict:
    """Hours by stage from exact prompt lengths and the timed rates. Steered phrases at 16 tokens (conservative);
    full generations (N check, N-cut) at 256 tokens (conservative) and at the cached §24 output length (typical).
    Pairs unknown before B is generated: half of P0 by default (rev 1's 'about 15')."""
    rp, rd, f, c = t["prefill_s_per_token"], t["decode_s_per_token"], t["first_step_s"], t["copy_s"]
    gen = lambda n: c + f + max(n - 1, 0) * rd  # noqa: E731
    g_mean, g_max = gen(t["mean_new_tokens_unsteered"]), gen(MAX_NEW)
    plen = lambda kind, qs: sum(len(run.engine.input_ids(run.item(kind, q))) - 1 for q in qs)  # noqa: E731
    G, P0 = run.p.G, run.p.P0
    n_pairs = len(P0) // 2 if n_pairs is None else n_pairs
    out_len = [len(run.engine.encode(run.p.by_q[q].output)) for q in G]
    full_max = lambda k: k * gen(MAX_NEW_FULL)  # noqa: E731
    n_set = len(run.layers) * len(run.alphas)
    nprompt = lambda qs: sum(len(run.engine.encode(run.engine.chat_text(sel.build_arm_input(run.p.by_q[q], "N").prompt)))
                             for q in qs) * rp  # noqa: E731
    cutp = sum(len(run.engine.encode(run.engine.chat_text(sel.build_arm_input(run.p.by_q[q], "Ncut").prompt))) for q in G) * rp
    a_G, a_P, b_P = plen("A", G) * rp, plen("A", P0) * rp, plen("B", P0) * rp
    nck = G[:run.n_check]
    secs = {
        "repro": a_G + a_P + b_P + (len(G) + 2 * len(P0)) * g_mean,
        "n_check": nprompt(nck) + full_max(len(nck)),
        "sanity": (a_P * n_pairs / max(len(P0), 1)) + n_pairs * (2 + len(run.layers)) * g_mean,
        "sweep": a_G + len(G) * n_set * g_max,
        "ncut": cutp + full_max(len(G)),
        "cut_all_settings": cutp * 1.1 + len(G) * (1 + n_set) * g_max,
        "random_k1": a_G + len(G) * g_max,
    }
    typical = dict(secs)
    typical["n_check"] = nprompt(nck) + sum(gen(n) for n in out_len[:len(nck)])
    typical["ncut"] = cutp + sum(gen(n) for n in out_len)
    typical["cut_all_settings"] = cutp * 1.1 + len(G) * (1 + n_set) * g_mean
    total, total_typ = sum(secs.values()), sum(typical.values())
    return {"hours_by_stage": {k: v / 3600 for k, v in secs.items()}, "total_hours": total / 3600,
            "total_hours_typical": total_typ / 3600,
            "total_hours_random_all_settings": (total + (n_set - 1) * secs["random_k1"]) / 3600,
            "settings": n_set, "assumed_pairs": n_pairs}


# --- main --------------------------------------------------------------------------------------------------------

def plan(pops: Populations, log) -> None:
    r = pops.by_q
    log(f"G (gate, in-view dev refusals, never in estimation): {len(pops.G)} {pops.G}")
    log(f"P0 (pair candidates: marked, answerable, evidence not all in view, cached refusal): {len(pops.P0)}")
    log(f"  unanswerable not-in-view refusals left out: {len(pops.excluded_unanswerable)} {pops.excluded_unanswerable}")
    log("  pairs = P0 rows whose regenerated A refuses and regenerated B answers: needs A/B regeneration (--run)")
    log(f"  folds: G {sorted({r[q].fold for q in pops.G})}, P0 {sorted({r[q].fold for q in pops.P0})}; "
        f"G gold D1 in the cached note: {sum(bool(sel.gold_in_note(r[q])) for q in pops.G)}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--folds", default="0,1")
    ap.add_argument("--out", default="runs/exp43_llama_dev")
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--backend", default="hf", choices=("hf", "stub"))
    ap.add_argument("--threads", type=int, default=8)
    ap.add_argument("--n-check", type=int, default=N_CHECK)
    ap.add_argument("--timing-only", action="store_true")
    ap.add_argument("--run", action="store_true", help="every stage (only after the Advisor's build review)")
    args = ap.parse_args(argv)
    folds = [int(f) for f in args.folds.split(",")]
    if not set(folds) <= set(DEV):
        print(f"REFUSED: folds {sorted(set(folds) - set(DEV))} are not development folds; §43 stage 1 is folds 0-1 only")
        return 2
    log = lambda s: print(s, flush=True)  # noqa: E731
    pops = populations(load_records(folds, args.runs))
    plan(pops, log)
    if folds == list(DEV) and len(pops.G) != EXPECT_G:
        log(f"WARNING: {len(pops.G)} gate rows, stage 0 counted {EXPECT_G}")
    if not (args.run or args.timing_only):
        log("plan only (no model): --timing-only for the 5-row timing, --run for the design run")
        return 0
    out = Path(args.out)
    t0 = time.perf_counter()
    if args.backend == "hf":
        load_env_token()
        missing = {k: v for k, v in FAMILY.laptop_env.items() if os.environ.get(k) != v}
        if missing and not __import__("torch").cuda.is_available():
            log(f"WARNING: laptop env not set ({sorted(missing)}); the fp32 load may hit the 22 GB guard")
        engine = st.HFEngine(FAMILY.model_id, args.threads, family=FAMILY)
        layers = list(FAMILY.sweep_layers)
    else:
        engine = st.StubEngine(FAMILY.model_id)
        layers = sorted({st.depth_layer(d, engine.n_layers) for d in FAMILY.sweep_depths})
    log(f"engine {engine.name}, {engine.n_layers} layers, width {engine.hidden}, loaded in {time.perf_counter() - t0:.0f} s; "
        f"layers {layers}")
    run = Run(engine, pops, out, layers, ALPHAS, args.n_check, log)
    if args.backend == "stub":
        engine.set_oracle(stub_oracle(run))
    tpath = run.dir / "timing.json"
    if tpath.exists():
        record = json.loads(tpath.read_text())
        if record["engine"] != engine.name:
            raise SystemExit(f"REFUSED: {tpath} was timed on {record['engine']!r}, this run uses {engine.name!r}")
    else:
        t = timing(run)
        record = {"engine": engine.name, "threads": args.threads, "timing": t, "projection": projection(run, t)}
        run.write_json("timing.json", record)
    pj, tt = record["projection"], record["timing"]
    log(f"timing: prefill {tt['prefill_s_per_token'] * 1000:.1f} ms/token, decode {tt['decode_s_per_token']:.2f} s/token, "
        f"copy {tt['copy_s']:.2f} s")
    log(f"projection ({pj['settings']} settings, {pj['assumed_pairs']} pairs assumed): {pj['total_hours']:.2f} h "
        f"conservative, {pj['total_hours_typical']:.2f} h typical, {pj['total_hours_random_all_settings']:.2f} h if Random "
        "runs at every setting; by stage " + ", ".join(f"{k} {v:.2f} h" for k, v in pj["hours_by_stage"].items()))
    if args.timing_only:
        log("Stopping (--timing-only).")
        return 0
    run.check_manifest()

    log("== (i) reproduction")
    rep = run.reproduction()
    run.write_json("repro.json", rep)
    log(f"reproduction {rep['rate']:.3f} over G + P0 ({rep['n']} rows; G {rep['rate_G']:.3f}); first id "
        f"{rep['first_match']}/{rep['n']}, phrase {rep['phrase_match']}/{rep['n']}; pairs {len(rep['pairs'])} of "
        f"{len(pops.P0)} candidates")
    if not rep["pass"]:
        log(f"reproduction below {st.REPRO_GATE}: stop (exit {EXIT_REPRO})")
        return EXIT_REPRO
    nck = run.n_check_rows()
    run.write_json("ncheck.json", nck)
    log(f"N check: first id {nck['first_match']}/{nck['n']}, marker {nck['marker']}/{nck['n']}, refusal "
        f"{nck['refusal_match']}/{nck['n']}, byte-exact {nck['exact']}/{nck['n']} ({nck['bar']})")
    if not nck["pass"]:
        log(f"N check failed: the full-generation path does not reproduce the cache (exit {EXIT_NCHECK})")
        return EXIT_NCHECK
    pairs, G = rep["pairs"], rep["G_ok"]
    if len(pairs) < MIN_PAIRS:
        log(f"{len(pairs)} pairs (< {MIN_PAIRS}): no direction can be estimated; Part A closes for Llama (exit {EXIT_PAIRS})")
        return EXIT_PAIRS

    log(f"== (iii) directions from {len(pairs)} pairs")
    for L, s in run.directions(pairs).items():
        log(f"  L{L}: ||v|| {s['v_norm']:.3f}, mean||resid_A|| {s['mean_resid_A_norm']:.3f}, ratio {s['v_over_resid']:.4f}")

    log("== (iv) sanity S")
    san = run.sanity(pairs)
    run.write_json("sanity.json", san)
    log(f"final-layer overwrite first-token rate {san['final_overwrite_rate']:.3f}; zero add byte-exact "
        f"{san['zero_exact_all']}; self-overwrite byte-exact {san['self_exact_all']}")
    if not san["pass"]:
        log(f"sanity S failed (exit {EXIT_SANITY})")
        return EXIT_SANITY

    log(f"== (v) sweep, cut, random on {len(G)} reproduced gate rows")
    gate = run.sweep(G)
    gate.update({"n_pairs": len(pairs), "pairs": pairs, "G_ok": G, "repro_rate": rep["rate"], "sanity_pass": san["pass"],
                 "ans_min": ans_min(len(G)),
                 "G_dropped": [{"question_id": q, "reason": "regenerated A does not refuse (cached refusal not reproduced)",
                                "A_first_match": v["first_match"]} for q, v in rep["G"].items() if not v["ok"]]})
    run.write_json("gate.json", gate)
    for k in gate["order"]:
        e = gate["table"][k]
        log(f"  {k}: ans {e['steer']['ans']}/{e['steer']['n']}, degen {e['steer']['degenerate']}, gold {e['steer']['gold']}"
            f", gold-cut diff {e['gold_diff']}, random {None if e['random'] is None else e['random']['ans']} "
            f"(<= {e['random_bound']:.1f}) -> {e['pass']}")
    log(f"chosen {gate['chosen']} (rule order); highest-ans alternative {gate['alt_rule_choice']} (descriptive)")
    run.write_json("passes.json", run.passes)
    log(f"done; forward passes {run.passes}. Report: scripts/exp43_llama_report.py --run-dir {run.dir}")
    return 0


def stub_oracle(run: Run) -> dict[str, str]:
    """Stub only: A reproduces the cached refusal; B answers on P0; N reproduces the cached output; N-cut writes a
    note and a refusal. Keyed by input text, as StubEngine.set_oracle wants."""
    texts = {}
    for q in sorted(set(run.p.G) | set(run.p.P0)):
        rec = run.p.by_q[q]
        a = run.item("A", q)
        texts[st.sha256(run.engine.chat_text(a.prompt) + a.continuation)] = sel.split_note(rec.output)[1]
        if q in run.p.P0:
            b = run.item("B", q)
            texts[st.sha256(run.engine.chat_text(b.prompt) + b.continuation)] = " the answer"
        n = run.item("N", q)
        texts[st.sha256(run.engine.chat_text(n.prompt))] = rec.output.strip()
        c = run.item("Ncut", q)
        texts[st.sha256(run.engine.chat_text(c.prompt))] = "nothing on this.\nAnswer: unknown"
    return texts


if __name__ == "__main__":
    raise SystemExit(main())
