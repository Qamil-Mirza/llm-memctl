"""Regenerate exp51-technical-report-single.tex by inlining every \\input{sections/...} of main.tex.
The single file still needs refs.bib and figures/fig2-tradeoff.pdf beside it. Run: python3 flatten.py"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def expand(text: str) -> str:
    def sub(m):
        return expand((HERE / (m.group(1) + ".tex")).read_text()).rstrip("\n")
    return re.sub(r"^\\input\{(sections/[^}]+)\}", sub, text, flags=re.M)


head = "% GENERATED by flatten.py from main.tex and sections/*.tex. Do not edit; edit the sources and regenerate.\n"
(HERE / "exp51-technical-report-single.tex").write_text(head + expand((HERE / "main.tex").read_text()))
print("wrote exp51-technical-report-single.tex")
